// Generates src/generated/shadcn-bridge.css from src/theme/shadcn-map.json (P1.4-T01).
//
//   node scripts/generate-bridge.mjs           write the bridge
//   node scripts/generate-bridge.mjs --check   fail if the committed bridge differs from a fresh build
//
// The bridge maps shadcn's variable names onto the semantic contract, so components never see a
// raw colour and a tenant theme (resolved --sem-* variables) restyles every component.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src', 'generated', 'shadcn-bridge.css');
const map = JSON.parse(
  fs.readFileSync(path.join(root, 'src', 'theme', 'shadcn-map.json'), 'utf8'),
);
const { SEMANTIC_VARIABLE_NAMES } = await import(
  pathToFileURL(
    path.join(
      root,
      '..',
      'design-tokens',
      'src',
      'generated',
      'ts',
      'tokens.ts',
    ),
  ).href
);

const known = new Set(SEMANTIC_VARIABLE_NAMES);
const targets = [
  ...Object.values(map.colors),
  map.radius,
  map.fontSans,
  map.shadow,
  map.densityFactor,
  map.typeScale,
];
const unknown = targets.filter((t) => !known.has(t));
if (unknown.length) {
  console.error(
    `ui-react: shadcn-map.json targets unknown variables: ${unknown.join(', ')}`,
  );
  process.exit(1);
}

// Tailwind v4 defaults, scaled by the tenant's type scale and density.
const TEXT = { xs: 0.75, sm: 0.875, base: 1, lg: 1.125, xl: 1.25, '2xl': 1.5 };
const colors = Object.entries(map.colors);
const lines = [
  '/* GENERATED by libs/ui-react/scripts/generate-bridge.mjs from src/theme/shadcn-map.json.',
  '   Do not edit. Run "pnpm nx run @byteflock/ui-react:build" and commit the result. */',
  '',
  ':root {',
  ...colors.map(([name, sem]) => `  --${name}: var(${sem});`),
  // Capped so a "full" tenant radius makes controls pills (all are 36px tall or less) while
  // dialogs and popovers keep rounded corners instead of turning into pills.
  `  --radius: min(var(${map.radius}), 1.5rem);`,
  '}',
  '',
  '@theme inline {',
  ...colors.map(([name]) => `  --color-${name}: var(--${name});`),
  '  --radius-sm: calc(var(--radius) - 4px);',
  '  --radius-md: calc(var(--radius) - 2px);',
  '  --radius-lg: var(--radius);',
  '  --radius-xl: calc(var(--radius) + 4px);',
  `  --font-sans: var(${map.fontSans});`,
  `  --shadow-md: var(${map.shadow});`,
  `  --spacing: calc(0.25rem * var(${map.densityFactor}));`,
  ...Object.entries(TEXT).map(
    ([k, rem]) => `  --text-${k}: calc(${rem}rem * var(${map.typeScale}));`,
  ),
  '}',
  '',
  "/* `dark:` utilities follow the tenant's appearance attribute, not only the OS setting. */",
  '@custom-variant dark {',
  '  &:where([data-appearance="dark"], [data-appearance="dark"] *) {',
  '    @slot;',
  '  }',
  '  @media (prefers-color-scheme: dark) {',
  '    &:where([data-appearance="system"], [data-appearance="system"] *) {',
  '      @slot;',
  '    }',
  '  }',
  '}',
  '',
  '@layer base {',
  '  * {',
  '    border-color: var(--color-border);',
  '    outline-color: color-mix(in oklab, var(--color-ring) 50%, transparent);',
  '  }',
  '  body {',
  '    background-color: var(--color-background);',
  '    color: var(--color-foreground);',
  '    font-family: var(--font-sans);',
  '  }',
  '}',
  '',
];
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  const committed = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (committed !== text) {
    console.error(
      'ui-react: src/generated/shadcn-bridge.css is stale. Run "pnpm nx run @byteflock/ui-react:build" and commit it.',
    );
    process.exit(1);
  }
  console.log('ui-react: shadcn-bridge.css is up to date');
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const changed = !fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text;
  if (changed) fs.writeFileSync(out, text);
  console.log(
    `ui-react: shadcn-bridge.css ${changed ? 'written' : 'unchanged'} (${colors.length} colours)`,
  );
}

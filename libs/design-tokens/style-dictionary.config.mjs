// Style Dictionary 5 configuration for @byteflock/design-tokens (ADR-003, SPECS/phases/P1.2).
//
// Sources are DTCG 2025.10 files under tokens/. Outputs (committed, never hand-edited):
//   css/semantic.css             --sem-* variables: light on :root, dark under [data-appearance="dark"],
//                                density and type-scale under [data-density] / [data-type-scale]
//   ts/tokens.ts                 SEMANTIC_VARIABLE_NAMES, SEMANTIC_DEFAULTS_LIGHT/DARK, SCALES
//   json/semantic.light.json     name → value
//   json/semantic.dark.json      name → value
//   json/scales.json             enum → value tables used by the theme resolver (P1.3)
//
// Primitives are private: they never become CSS variables. Only `semantic.*` and `set.*` do.

const HEADER =
  'Generated by @byteflock/design-tokens (style-dictionary.config.mjs). Do not edit.';

// --- value serialisation -------------------------------------------------------------------

const unitValue = (v) =>
  typeof v === 'object' && v !== null && 'value' in v
    ? `${v.value}${v.unit}`
    : String(v);

function serialise(token) {
  const type = token.$type ?? token.type;
  const value = token.$value ?? token.value;
  switch (type) {
    case 'dimension':
    case 'duration':
      return unitValue(value);
    case 'fontFamily':
      return (Array.isArray(value) ? value : [value])
        .map((f) => (/\s/.test(f) ? `"${f}"` : f))
        .join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'shadow': {
      const one = (s) =>
        [s.offsetX, s.offsetY, s.blur, s.spread].map(unitValue).join(' ') +
        ` ${s.color}`;
      return Array.isArray(value) ? value.map(one).join(', ') : one(value);
    }
    default:
      return String(value);
  }
}

// --- classification ------------------------------------------------------------------------

/** Splits the dictionary into the groups every output needs. Deterministic: sorted by name. */
function classify(dictionary) {
  const light = {};
  const dark = {};
  const shared = {};
  const sets = { density: {}, 'type-scale': {} };
  const primitives = {};

  for (const token of dictionary.allTokens) {
    const [layer, ...rest] = token.path;
    const value = serialise(token);
    if (layer === 'semantic' && (rest[0] === 'light' || rest[0] === 'dark')) {
      (rest[0] === 'light' ? light : dark)[`--sem-${rest.slice(1).join('-')}`] =
        value;
    } else if (layer === 'semantic') {
      shared[`--sem-${rest.join('-')}`] = value;
    } else if (layer === 'set') {
      sets[rest[0]][rest[1]] = token.$value ?? token.value;
    } else if (layer === 'primitive') {
      primitives[rest.join('.')] = value;
    }
  }

  const sortObj = (o) =>
    Object.fromEntries(
      Object.entries(o).sort(([a], [b]) => a.localeCompare(b)),
    );
  const defaults = {
    '--sem-density-factor': String(sets.density.comfortable),
    '--sem-type-scale': String(sets['type-scale'].md),
  };
  const lightAll = sortObj({ ...light, ...shared, ...defaults });
  const darkAll = sortObj({ ...lightAll, ...dark });

  const pick = (prefix) =>
    Object.fromEntries(
      Object.entries(primitives)
        .filter(([k]) => k.startsWith(prefix))
        .map(([k, v]) => [k.slice(prefix.length), v]),
    );

  const scales = {
    radius: pick('radius.'),
    density: sets.density,
    typeScale: sets['type-scale'],
    elevation: pick('shadow.'),
    fontStacks: pick('font.family.'),
  };

  return {
    light: sortObj(light),
    dark: sortObj(dark),
    shared: sortObj(shared),
    sets,
    lightAll,
    darkAll,
    scales,
  };
}

// --- formats -------------------------------------------------------------------------------

const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')}\n}\n`;

function cssFormat({ dictionary }) {
  const c = classify(dictionary);
  const parts = [
    `/* ${HEADER} */\n`,
    block(':root', c.lightAll),
    block(':root[data-appearance="dark"],\n[data-appearance="dark"]', c.dark),
    ...Object.entries(c.sets.density).map(([k, v]) =>
      block(`[data-density="${k}"]`, { '--sem-density-factor': String(v) }),
    ),
    ...Object.entries(c.sets['type-scale']).map(([k, v]) =>
      block(`[data-type-scale="${k}"]`, { '--sem-type-scale': String(v) }),
    ),
  ];
  return parts.join('\n');
}

const tsObject = (obj, indent = '  ') =>
  `{\n${Object.entries(obj)
    .map(
      ([k, v]) =>
        `${indent}${JSON.stringify(k)}: ${typeof v === 'object' ? tsObject(v, indent + '  ') : JSON.stringify(v)},`,
    )
    .join('\n')}\n${indent.slice(2)}}`;

function tsFormat({ dictionary }) {
  const c = classify(dictionary);
  const names = Object.keys(c.lightAll);
  return [
    `// ${HEADER}`,
    '',
    `export const SEMANTIC_VARIABLE_NAMES = [\n${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}\n] as const;`,
    '',
    'export type SemanticVariableName = (typeof SEMANTIC_VARIABLE_NAMES)[number];',
    '',
    `export const SEMANTIC_DEFAULTS_LIGHT: Readonly<Record<SemanticVariableName, string>> = ${tsObject(c.lightAll)};`,
    '',
    `export const SEMANTIC_DEFAULTS_DARK: Readonly<Record<SemanticVariableName, string>> = ${tsObject(c.darkAll)};`,
    '',
    `/** Enum → value tables for the theme resolver (THEME-03). */\nexport const SCALES = ${tsObject(c.scales)} as const;`,
    '',
  ].join('\n');
}

const json =
  (pickFn) =>
  ({ dictionary }) =>
    JSON.stringify(pickFn(classify(dictionary)), null, 2) + '\n';

// --- config factory ------------------------------------------------------------------------

/** @param {string} buildPath absolute or relative output directory, ending with a slash */
export function createConfig(buildPath) {
  return {
    source: ['tokens/**/*.tokens.json'],
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'error' },
    hooks: {
      formats: {
        'byteflock/css': cssFormat,
        'byteflock/ts': tsFormat,
        'byteflock/json-light': json((c) => c.lightAll),
        'byteflock/json-dark': json((c) => c.darkAll),
        'byteflock/json-scales': json((c) => c.scales),
      },
    },
    platforms: {
      byteflock: {
        buildPath,
        transforms: ['name/kebab'],
        files: [
          { destination: 'css/semantic.css', format: 'byteflock/css' },
          { destination: 'ts/tokens.ts', format: 'byteflock/ts' },
          {
            destination: 'json/semantic.light.json',
            format: 'byteflock/json-light',
          },
          {
            destination: 'json/semantic.dark.json',
            format: 'byteflock/json-dark',
          },
          { destination: 'json/scales.json', format: 'byteflock/json-scales' },
        ],
      },
    },
  };
}
